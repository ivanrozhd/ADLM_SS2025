import sam_segmentor
import torch
from segmentation_metrics_calculator import evaluate_lung_masks
from plot import plot_metrics
import pandas as pd

######################### Define necessary paths and configurations ###########################################################################
use_case = "add_lung_nodules"
seeds = [1122, 1469, 2790, 3933, 4170, 4462, 5210, 5935, 7177]
input_image_folder = "generated_images/add_lung_nodules"  # Folder with images generated by prompt-to-prompt-Stablediffusion
run_sam_segmentor = True  # if True, run SAM models on input images, otherwise load precomputed results
# for plots
x_label='crossReplace_selfReplace-steps'
config_order = ['0.8_0.6', '0.5_0.6', '0.2_0.6', '0.8_0.4', '0.5_0.4', '0.2_0.4', '0.8_0.2', '0.5_0.2', '0.2_0.2', '0.0_0.0']

###############################################################################################################################################


# Get segmentation results of SAM segmentor
sam_segmentor_results_path = f"evaluation/segment_results_{use_case}.pt"
if run_sam_segmentor:
    sam_segmentor_results = sam_segmentor.segment(input_image_folder=input_image_folder, output_file_path=sam_segmentor_results_path)
else:
    sam_segmentor_results = torch.load(sam_segmentor_results_path, map_location=torch.device('cpu'), weights_only=False)

# DataFrame with metrics per lung, seed and editing config: ['Seed', 'Editing Config', 'Lung', 'IoU', 'Dice', 'ASD', 'HD']
metrics_df = evaluate_lung_masks(sam_segmentor_results, use_case="_" + use_case)

# Filter seeds and editing configs
metrics_df = metrics_df[metrics_df['Seed'].isin(seeds)]
metrics_df = metrics_df[metrics_df['Editing Config'].isin(config_order)]

# Average metrics per seed and editing config: ['Seed', 'Editing Config', 'IoU', 'Dice', 'ASD', 'HD']
avg_per_seed_config_metrics_df = (
    metrics_df
    .drop(columns=['Lung'])
    .groupby(['Seed', 'Editing Config'], as_index=False)
    .mean(numeric_only=True).round(2)   # average IoU, Dice, ASD, HD
)

# Define the baseline 'Editing Config' 
if use_case.startswith('add_') or use_case.startswith('remove_'):
    avg_per_seed_config_metrics_df['Editing Config'] = avg_per_seed_config_metrics_df['Editing Config'].apply(lambda x: '0.0_0.0' if x == 'No CrossAttn Control' else x)
elif use_case.startswith('reweight_'):
    baseline_metrics = {'Editing Config': '0', 'Dice': 1.0, 'IoU': 1.0, 'ASD': 0.0, 'HD': 0.0}
    baseline_rows = []
    for seed in avg_per_seed_config_metrics_df['Seed'].unique():
        row = baseline_metrics.copy()
        row['Seed'] = seed
        baseline_rows.append(row)
    baseline_df = pd.DataFrame(baseline_rows)
    baseline_df = baseline_df[avg_per_seed_config_metrics_df.columns]
    avg_per_seed_config_metrics_df = pd.concat([avg_per_seed_config_metrics_df, baseline_df], ignore_index=True)
else:
    raise ValueError(f"Unknown use case: {use_case}")

# Plot metrics
for metric in ['Dice', 'ASD', 'HD']:
    if metric == 'Dice':
        title = 'Dice score across seeds'
        y_label = 'Dice score'
        legend_loc = 'lower right'
    else:
        title = f'{metric} across seeds'
        y_label = metric
        legend_loc = 'upper right'
        
    plot_metrics(plot_df=avg_per_seed_config_metrics_df, 
                 metric=metric, 
                 title=title,
                 config_order=config_order, 
                 x_label=x_label, 
                 y_label=y_label, 
                 legend_loc=legend_loc, 
                 output_folder='evaluation/metrics_plots/' + use_case)
